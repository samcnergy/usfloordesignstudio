// Writes supabase/migrations/0002_seed_standard_catalog.sql from src/lib/standard-catalog.ts.
// Run: node --experimental-strip-types scripts/generate-seed.mjs
import { writeFileSync } from "node:fs";
import { STANDARD_CATALOG } from "../src/lib/standard-catalog.ts";

const q = (v) => (v === null || v === undefined ? "null" : typeof v === "number" || typeof v === "boolean" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => `array[${a.join(",")}]::numeric[]`;

let sql = `-- Standard starting catalog. Generated by scripts/generate-seed.mjs; do not edit by hand.
-- Safe to run more than once: existing rows with the same id are left alone.

`;
sql += "insert into public.ds_cabinets (id, code, name, category, style, widths, heights, default_height, depth, mount_height, sort, active) values\n";
sql += STANDARD_CATALOG.cabinets
  .map((c) => `  (${q(c.id)}, ${q(c.code)}, ${q(c.name)}, ${q(c.category)}, ${q(c.style)}, ${arr(c.widths)}, ${arr(c.heights)}, ${c.default_height}, ${c.depth}, ${q(c.mount_height)}, ${c.sort}, true)`)
  .join(",\n");
sql += "\non conflict (id) do nothing;\n\n";
sql += "insert into public.ds_finishes (id, name, vendor, color_hex, sort, active) values\n";
sql += STANDARD_CATALOG.finishes.map((f) => `  (${q(f.id)}, ${q(f.name)}, ${q(f.vendor)}, ${q(f.color_hex)}, ${f.sort}, true)`).join(",\n");
sql += "\non conflict (id) do nothing;\n\n";
sql += "insert into public.ds_countertops (id, name, color_hex, thickness, sort, active) values\n";
sql += STANDARD_CATALOG.countertops.map((c) => `  (${q(c.id)}, ${q(c.name)}, ${q(c.color_hex)}, ${c.thickness}, ${c.sort}, true)`).join(",\n");
sql += "\non conflict (id) do nothing;\n";

writeFileSync(new URL("../supabase/migrations/0002_seed_standard_catalog.sql", import.meta.url), sql);
console.log("wrote 0002_seed_standard_catalog.sql");
